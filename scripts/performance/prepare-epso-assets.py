"""Prepare supplied EPSO portfolio screenshots; preserve the user's source files.

Pass the screenshot directory as the only argument. Originals for the lightbox
are WebP copies; content-hashed Vite variants serve the page and portfolio grid.
"""
from pathlib import Path
import hashlib
import json
import sys
from PIL import Image

root = Path(__file__).resolve().parents[2]
source = Path(sys.argv[1])
public = root / "public/projects/epso"
assets = root / "src/assets/epso"
public.mkdir(parents=True, exist_ok=True)
assets.mkdir(parents=True, exist_ok=True)
imports, entries, records = [], [], []
for index, path in enumerate(sorted(source.glob("*.png"))):
    image = Image.open(path).convert("RGB")
    key = path.stem
    url = f"/projects/epso/{key}.webp"
    image.save(public / f"{key}.webp", quality=86, method=6)
    digest = hashlib.sha256(image.tobytes()).hexdigest()[:8]
    variants = []
    for width in sorted({min(w, image.width) for w in (480, 840, 1440)}):
        filename = f"{key}-{digest}-{width}.webp"
        image.resize((width, round(image.height * width / image.width)), Image.Resampling.LANCZOS).save(assets / filename, quality=78, method=6)
        variable = f"shot{index}_{width}"
        imports.append(f'import {variable} from "./{filename}?no-inline";')
        variants.append(f"{{ src: {variable}, width: {width} }}")
    entries.append(f"  {json.dumps(url)}: [{', '.join(variants)}],")
    records.append(f"  {json.dumps(key)}: {{ src: {json.dumps(url)}, width: {image.width}, height: {image.height} }},")
(assets / "images.ts").write_text("// Generated by scripts/performance/prepare-epso-assets.py.\n" + "\n".join(imports) + "\nexport const epsoImages = {\n" + "\n".join(entries) + "\n};\n")
(root / "src/data/epsoScreenshots.ts").write_text("// Supplied EPSO screenshots, 22 October 2026. Generated dimensions and local sources.\nexport const EPSO_SCREENSHOTS = {\n" + "\n".join(records) + "\n} as const;\n")
print(f"Prepared {len(records)} EPSO screenshots and responsive variants.")
