"""Emit small, content-hashed Vite assets; leave all supplied originals untouched.

Run with Pillow after changing source artwork. Mobile sources deliberately cap
decorative image resolution rather than downloading desktop art on high-DPR phones.
"""
from pathlib import Path
import hashlib
import json
import re
import shutil
import sys
from PIL import Image

root = Path(__file__).resolve().parents[2]
public = root / "public"
destination = root / "src/assets/responsive"
destination.mkdir(parents=True, exist_ok=True)
repair_transparency = "--repair-transparency" in sys.argv


def manifest(name, sources):
    imports, entries = [], []
    for index, (key, source, widths, quality) in enumerate(sources):
        image = Image.open(public / source)
        # Retain transparency in the logos, portraits and illustrations.
        palette_alpha = "transparency" in image.info
        image = image.convert("RGBA" if "A" in image.getbands() or palette_alpha else "RGB")
        variants = []
        stem = re.sub(r"[^a-z0-9-]", "-", Path(source).stem.lower())
        digest = hashlib.sha256(source.encode()).hexdigest()[:8]
        for width in sorted({min(width, image.width) for width in widths}):
            filename = f"{stem}-{digest}-{width}.webp"
            if not repair_transparency or palette_alpha or not (destination / filename).is_file():
                image.resize((width, round(image.height * width / image.width)), Image.Resampling.LANCZOS).save(
                    destination / filename, quality=quality, method=6
                )
            variable = f"asset{index}_{width}"
            imports.append(f'import {variable} from "./{filename}?no-inline";')
            variants.append(f"{{ src: {variable}, width: {width} }}")
        entries.append(f"  {json.dumps(key)}: [{', '.join(variants)}],")
    (destination / f"{name}.ts").write_text(
        "// Generated by scripts/performance/prepare-responsive-assets.py.\n"
        + '\n'.join(imports)
        + f"\n\nexport const {name} = {{\n" + '\n'.join(entries) + "\n};\n"
    )


home = []
for theme in ("dark", "light", "robot"):
    home.append((f"chimp-{theme}", f"art/orbit/chimp-hero-{theme}.webp", (480, 640, 800, 1200), 76))
for name in ("cinematic-moon", "moon-back", "moon-middle", "moon-front"):
    home.append((name, f"art/orbit/{name}.webp", (480, 850, 1254) if name == "cinematic-moon" else (960, 1536, 1920), 70))
for theme in ("dark", "light"):
    for service in ("websites", "apps", "automation", "branding"):
        home.append((f"{service}-{theme}", f"services/{service}-{theme}.webp", (320, 640, 960), 74))
    home.append((f"person-{theme}", f"people/cormac-mccann-{theme}.webp", (480, 720), 74))
for name, source in (("clubrovia", "projects/clubrovia/imac-dark.webp"), ("mckevitts", "projects/mckevitts/brand-presentation.jpg")):
    home.append((name, source, (480, 640, 840, 1200), 78))
manifest("homeImages", home)

# A mobile terrain plate replaces the three overlapping desktop planes.
back = Image.open(public / "art/orbit/moon-back.webp").convert("RGBA")
plate = Image.new("RGBA", back.size)
for name in ("moon-back", "moon-middle", "moon-front"):
    layer = Image.open(public / f"art/orbit/{name}.webp").convert("RGBA")
    plate.alpha_composite(layer, (0, back.height - layer.height))
plate.resize((960, round(plate.height * 960 / plate.width)), Image.Resampling.LANCZOS).save(
    destination / "mobile-terrain.webp", quality=68, method=6
)

# Only project artwork referenced by portfolio data is included, not unrelated files.
sources = set()
for filename in ("projects.ts", "portfolioCaptures.ts", "brandArtwork.ts"):
    sources.update(re.findall(r'"(/projects/[^"\n]+\.(?:webp|png|jpg|jpeg|avif))"', (root / "src/data" / filename).read_text()))
manifest("portfolioImages", [(source, source.lstrip("/"), (480, 840, 1440), 80) for source in sorted(sources) if (public / source.lstrip("/")).is_file()])

manifest("headerImages", [(theme, source, (128, 256, 320), 78) for theme, source in (("dark", "kamrok-logo.png"), ("light", "kamrok-logo-bright-mode.png"))])
for font in (public / "fonts").glob("*.woff2"):
    shutil.copyfile(font, destination / font.name)
for theme in ("dark", "light"):
    shutil.copyfile(public / f"certifications/lovable-expert-app-builder-full-on-{theme}.svg", destination / f"lovable-{theme}.svg")
print(f"Prepared homepage, header, fonts and {len(sources)} portfolio sources. Originals retained.")
